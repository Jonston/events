/**
 * Метка браузера для гостя.
 *
 * Заявку оставляют и без входа, а повторную принимать не стоит: мастеру
 * достаются два одинаковых контакта, а человек не понимает, дошла первая
 * или нет. Сессии у нас нет — API работает по токену и без состояния,
 * — поэтому метку хранит сам браузер и присылает вместе с заявкой.
 *
 * Это не защита от злого умысла: почистить куки может каждый. Это защита
 * от второго нажатия кнопки, и большего от неё не требуется.
 */
export function useGuestKey() {
  const key = useCookie<string | null>('guest_key', {
    maxAge: 60 * 60 * 24 * 365,
    sameSite: 'lax',
    // Читается на клиенте перед отправкой формы, поэтому не httpOnly.
    default: () => null
  })

  function ensure(): string {
    if (!key.value) {
      key.value = crypto.randomUUID()
    }

    return key.value
  }

  return { key, ensure }
}
