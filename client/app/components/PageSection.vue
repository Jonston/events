<script setup lang="ts">
/**
 * Полоса страницы.
 *
 * Снаружи она всегда во всю ширину окна — фон, разделители и заливка идут
 * от края до края, иначе тёмные и тонированные блоки обрывались бы по краям
 * колонки. Внутри содержимое по умолчанию держится колонки страницы: так
 * заголовки, текст и карточки на всех экранах стоят по одной вертикали.
 *
 * `width="full"` оставлен для того, что осмысленно только во всю ширину —
 * карты и полосы во весь экран.
 */
withDefaults(defineProps<{ width?: 'page' | 'full' }>(), { width: 'page' })
</script>

<template>
  <section>
    <div :class="width === 'page' ? 'mx-auto max-w-page px-6' : ''">
      <slot />
    </div>
  </section>
</template>
