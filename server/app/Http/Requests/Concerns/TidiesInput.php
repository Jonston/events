<?php

declare(strict_types=1);

namespace App\Http\Requests\Concerns;

/**
 * Мелкая уборка того, что приходит формой с картинками.
 *
 * Такая форма уходит как `multipart/form-data`, а этот формат по дороге
 * меняет значения: числа и флаги становятся строками, переводы строк —
 * парой CR+LF. Обе поправки нужны каждой форме с файлами, поэтому лежат
 * рядом, а не переписываются в каждом запросе.
 */
trait TidiesInput
{
    /**
     * Приводит флажки формы к настоящим булевым.
     *
     * Правило `boolean` строку «0» пропускает, но в сравнении она ведёт себя
     * как истина: без этого «убрать обложку» молча не срабатывает.
     *
     * Отсутствующие ключи не подставляем: «поле не прислали» и «прислали
     * выключенным» — разные вещи, и во втором случае снялась бы публикация.
     */
    protected function castFlags(string ...$flags): void
    {
        foreach ($flags as $flag) {
            if ($this->has($flag)) {
                $this->merge([$flag => $this->boolean($flag)]);
            }
        }
    }

    /**
     * Оставляет в тексте один вид перевода строки.
     *
     * Браузер отправляет многострочное поле с CR+LF, а при разборе страницы
     * возвращает те же строки уже без CR. Пока текст хранится «как пришёл»,
     * разметка от сервера и от клиента расходятся на каждом абзаце,
     * и страница перерисовывается заново после гидрации.
     */
    protected function normalizeNewlines(string ...$fields): void
    {
        foreach ($fields as $field) {
            $value = $this->input($field);

            if (is_string($value)) {
                $this->merge([$field => str_replace(["\r\n", "\r"], "\n", $value)]);
            }
        }
    }
}
