    /**
     * Отзывы пишут участники — значит, каждому нужен свой аккаунт.
     * Берём уже засеянных участников, а не создаём отдельных «авторов»:
     * иначе в списке пользователей появились бы люди, которых нет.
     *
     * @param  array<int, array{0: int, 1: string}>  $reviews
     */
    private function seedReviews(Master $master, array $reviews, int $masterIndex): void
    {
        $members = User::query()
            ->whereHas('roles', fn ($query) => $query->where('name', UserRole::Member->value))
            ->orderBy('id')
            ->get();

        if ($members->isEmpty()) {
            return;
        }

        foreach ($reviews as $position => [$rating, $body]) {
            // Сдвиг по мастеру и по кругу: у разных мастеров отзывы от разных
            // людей, но участники не кончаются, сколько бы мастеров ни было.
            // Один отзыв на пару «мастер — человек» гарантирует индекс в базе.
            $author = $members[($masterIndex * 3 + $position) % $members->count()];

            Review::updateOrCreate(
                ['master_id' => $master->id, 'user_id' => $author->id],
                [
                    'rating' => $rating,
                    'body' => $body,
                    'status' => ReviewStatus::Published,
                    'moderated_at' => now(),
                ],
            );
        }
    }
